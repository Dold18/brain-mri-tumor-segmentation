"""Standalone checkpoint inference; no ground-truth labels or hosted API required."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch

from .model import UNet2D
from .preprocessing import normalize_mri


def load_checkpoint_model(checkpoint_path: str | Path, *, device: str = "cpu") -> tuple[UNet2D, dict]:
    path = Path(checkpoint_path)
    if not path.is_file():
        raise FileNotFoundError(f"Brain MRI Tumor Segmentation checkpoint not found: {path}")
    # `weights_only` avoids deserializing arbitrary user-defined pickle classes.
    state = torch.load(path, map_location="cpu", weights_only=True)
    if state.get("schema") != 1 or "model_settings" not in state:
        raise ValueError("Unsupported Brain MRI Tumor Segmentation checkpoint format")
    model = UNet2D(**state["model_settings"])
    model.load_state_dict(state["model_state"])
    model = model.to(torch.device(device)).eval()
    return model, state


@torch.inference_mode()
def predict_normalized_volume(model: UNet2D, normalized: np.ndarray, *,
                              batch_size: int = 8, device: str = "cpu") -> np.ndarray:
    """Infer `[X,Y,Z,C]` normalized MRI and return `[X,Y,Z]` tumor probabilities."""
    volume = np.asarray(normalized, dtype=np.float32)
    if volume.ndim != 4 or volume.shape[-1] != model.in_channels:
        raise ValueError(f"Expected [X,Y,Z,{model.in_channels}] normalized volume")
    if min(volume.shape[:2]) < 16 or batch_size < 1 or not np.isfinite(volume).all():
        raise ValueError("Invalid image dimensions, batch size, or nonfinite data")
    # Z,C,X,Y: one slice per observation, sharing preprocessing with training.
    slices = np.moveaxis(volume, (2, 3), (0, 1))
    predictions = []
    model.eval()
    for start in range(0, len(slices), batch_size):
        x = torch.from_numpy(np.ascontiguousarray(slices[start:start + batch_size])).to(device)
        scores = torch.sigmoid(model(x)).cpu().numpy()[:, 0]
        predictions.append(scores)
    probability_zhw = np.concatenate(predictions, axis=0)
    return np.ascontiguousarray(np.moveaxis(probability_zhw, 0, 2))


def predict_volume(model: UNet2D, raw_image: np.ndarray, checkpoint: dict, *,
                   batch_size: int = 8, device: str = "cpu") -> tuple[np.ndarray, np.ndarray]:
    """Run MRI normalization and real model inference; returns probabilities and binary mask."""
    cfg = checkpoint["preprocessing"]
    normal = normalize_mri(raw_image, lower_percentile=cfg["clip_low_percentile"],
                           upper_percentile=cfg["clip_high_percentile"])
    probabilities = predict_normalized_volume(model, normal, batch_size=batch_size, device=device)
    binary_mask = np.asarray(probabilities >= float(checkpoint["threshold"]), dtype=np.uint8)
    return probabilities, binary_mask


@torch.inference_mode()
def predict_cached_case(
    model: UNet2D,
    slices: np.ndarray,
    *,
    batch_size: int = 8,
    device: str | torch.device = "cpu",
) -> np.ndarray:
    """Predict normalized cached [Z,C,H,W] MRI; return probabilities [Z,H,W].

    The cache is generated by the exact same preprocessing as training. This
    function processes batches so callers may pass a memory-mapped array.
    """
    if slices.ndim != 4 or slices.shape[1] != model.in_channels:
        raise ValueError(f"Expected [Z,{model.in_channels},H,W] cached MRI, got {slices.shape}")
    if slices.shape[0] == 0 or min(slices.shape[-2:]) < 16 or batch_size < 1:
        raise ValueError("Invalid cache dimensions or batch size")
    model.eval()
    output = np.empty((slices.shape[0], slices.shape[2], slices.shape[3]), dtype=np.float32)
    for start in range(0, slices.shape[0], batch_size):
        chunk = np.asarray(slices[start:start + batch_size], dtype=np.float32)
        if not np.isfinite(chunk).all():
            raise ValueError("Nonfinite values in cached MRI")
        x = torch.from_numpy(np.ascontiguousarray(chunk)).to(device)
        p = torch.sigmoid(model(x)).cpu().numpy()[:, 0]
        output[start:start + len(p)] = p
    return output
